import unicodedata
from fontTools.ttLib import TTFont

def generate_cp(fn_input, fn_output_h, fn_output_c):
    font = TTFont(fn_input)
    codepoints = set()
    for table in font['cmap'].tables:
        for codepoint in table.cmap.keys():
            codepoints.add(codepoint)
    visible = []
    for cp in sorted(codepoints):
        try:
            char = chr(cp)
            name = unicodedata.name(char)
            visible.append(cp)
        except ValueError:
            continue  # not visible
    print(f"Total generated visible codepoints: {len(visible)}")

    with open(fn_output_h, "w", encoding="utf-8") as h:
        h.write("// Autogenerated codepoints.h\n")
        h.write("// font: ")
        h.write(fn_input)
        h.write("\n")
        h.write("#pragma once\n\n")
        h.write("extern const int codepoints[];\n")
        h.write("extern const int codepointCount;\n")

    with open(fn_output_c, "w", encoding="utf-8") as c:
        c.write("// Autogenerated codepoints.c\n")
        c.write("// font: ")
        c.write(fn_input)
        c.write("\n\n")

        c.write("#include \"codepoints.h\"\n\n")
        c.write(f"const int codepointCount = {len(visible)};\n")
        c.write("const int codepoints[] = {\n")
        for i, cp in enumerate(visible):
            c.write(f"  {cp},")
            if (i + 1) % 8 == 0:
                c.write("\n")
        c.write("\n};\n")

if __name__ == '__main__':
    import sys
    if (len(sys.argv)!=4):
        print(f"usage: {sys.argv[0]} <input.ttf> <output.h>")
    else:
        sys.exit(generate_cp(sys.argv[1], sys.argv[2], sys.argv[3]))
