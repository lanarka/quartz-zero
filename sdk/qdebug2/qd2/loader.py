"""
Loading of a compiled QuartzVM image (.bin) the same way load_program() does
it in vm.c, plus an optional .map file (address:label) generated by qasm.
"""

import os

# Fixed header layout, must stay in sync with the C loader:
#   [0:4]   magic number
#   [4]     bin_version (format of this file)
#   [5]     runtime_version (VM version the image targets)
#   [6:10]  entry point address (LE)
#   [10:14] code segment length (LE)
#   [14:18] data segment length (LE)
#   [18:22] data segment load address (LE)
BIN_MAGIC = bytes([0x7F, 0x51, 0x00, 0x7F])
BIN_VERSION = 0x04
HEADER_SIZE = 22


class ImageError(Exception):
    """Raised for any problem with a .bin file's format or contents."""
    pass


class Image:
    """Plain container holding a parsed .bin image: entry point, the raw
    code/data segments, where the data segment should be loaded in RAM, and
    a couple of version fields plus the original file path (for display)."""

    def __init__(self, entry, code, data, data_addr, bin_version, runtime_version, path):
        self.entry = entry
        self.code = code
        self.data = data
        self.data_addr = data_addr
        self.bin_version = bin_version
        self.runtime_version = runtime_version
        self.path = path


def load_image(path):
    """Read and validate a .bin file, returning an Image on success or
    raising ImageError/OSError on any format problem."""
    with open(path, "rb") as f:
        raw = f.read()

    if len(raw) < HEADER_SIZE:
        raise ImageError(f"'{path}' is too small to be a valid image file")

    header = raw[:HEADER_SIZE]
    if header[0:4] != BIN_MAGIC:
        raise ImageError(f"'{path}' has an invalid magic number")

    bin_version = header[4]
    runtime_version = header[5]
    entry = int.from_bytes(header[6:10], "little")
    code_len = int.from_bytes(header[10:14], "little")
    data_len = int.from_bytes(header[14:18], "little")
    data_addr = int.from_bytes(header[18:22], "little")

    if bin_version != BIN_VERSION:
        raise ImageError(f"unsupported image version (bin_version={bin_version})")

    # Code and data segments follow the header back-to-back, in that order.
    pos = HEADER_SIZE
    code = raw[pos:pos + code_len]
    if len(code) != code_len:
        raise ImageError("file is truncated (missing code)")
    pos += code_len

    data = raw[pos:pos + data_len]
    if len(data) != data_len:
        raise ImageError("file is truncated (missing data segment)")

    return Image(entry, code, data, data_addr, bin_version, runtime_version, path)


def sanitize_label(name):
    # qasm can emit labels containing "@" (e.g. for scoped/local labels);
    # replace it so the name is safe to display and doesn't clash with any
    # syntax-highlighting rules that treat "@" specially.
    return name.replace("@", "__")


def load_map(path):
    """Parse a .map file into a dict: addr -> [name, name, ...].

    Multiple labels can point at the same address, so each entry maps to a
    list; the first one is used as the "primary" display name elsewhere.
    Silently returns an empty dict if the file doesn't exist, since a map
    file is always optional.
    """
    labels = {}
    if not path or not os.path.isfile(path):
        return labels
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            addr_str, _, name = line.partition(":")
            try:
                addr = int(addr_str, 16)
            except ValueError:
                # Skip malformed lines rather than failing the whole load.
                continue
            labels.setdefault(addr, []).append(sanitize_label(name))
    return labels


def default_map_path(bin_path):
    # Convention used by qasm --map: same base name as the .bin, with a
    # .map extension instead.
    return os.path.splitext(bin_path)[0] + ".map"
